"""Scope guardrails shared by the two assistants. Pure functions, no I/O.

Each assistant has a designated area:
- Product Assistant: questions about how AI Career Companion works (answered only from its documentation).
- Career Assistant: the student's internship search, skills, applications and interview practice.

Layers (cheapest first):
1. `pre_check` (this module, no AI call): greetings and thanks get a fixed friendly reply; obvious prompt-injection
   attempts and over-long messages get a fixed refusal.
2. The Career Assistant's agent must classify each message (`scope`), and an out-of-scope message gets the fixed
   refusal below whatever the model wrote.
3. The Product Assistant answers only from retrieved documentation sections; with nothing relevant it replies
   that the documentation does not cover the question.
The refusal texts are fixed strings, never generated by the model.
"""

import re

MAX_MESSAGE_CHARS = 2000

PRODUCT = "product"
CAREER = "career"

REFUSAL = {
    PRODUCT: (
        "I can only answer questions about how AI Career Companion works: its features, how to use them, its "
        "architecture and the technology it uses. For example: \"How does job matching work?\" or \"How do I upload my resume?\""
    ),
    CAREER: (
        "I can only help with your internship search: finding and ranking internships that fit you, skill gaps, resume and "
        "cover-letter advice for applications, interview practice and tracking your applications. I can't help with "
        "unrelated topics. For questions about how the app itself works, please use the Product Assistant."
    ),
}

INJECTION_REPLY = {
    PRODUCT: "I can't change my instructions or share them. " + REFUSAL[PRODUCT],
    CAREER: "I can't change my instructions or share them. " + REFUSAL[CAREER],
}

GREETING_REPLY = {
    PRODUCT: (
        "Hello! I'm the Product Assistant. Ask me how AI Career Companion works: its features, how to upload a resume, "
        "how matching works, how to generate a cover letter or how to use interview preparation."
    ),
    CAREER: (
        "Hello! I'm your Career Assistant. I can find internships that fit your verified skills, explain your match scores "
        "and skill gaps, set up interview practice and help you track applications. What would you like to do?"
    ),
}

THANKS_REPLY = {
    PRODUCT: "You're welcome! Ask me anything else about how the product works.",
    CAREER: "You're welcome! Let me know if you want help with matches, skill gaps, interview practice or your applications.",
}

TOO_LONG_REPLY = f"That message is too long for me to handle. Please keep it under {MAX_MESSAGE_CHARS} characters."

_GREETING = re.compile(r"^\s*(hi+|hello+|hey+|hola|namaste|good\s+(morning|afternoon|evening)|greetings)\b[\s!.,?]*(there|team|assistant|bot)?[\s!.,?]*$", re.I)
_THANKS = re.compile(r"^\s*(thanks?( you)?( so much| a lot)?|thx|ty|ok(ay)?|cool|great|nice|got it|perfect|awesome|bye|goodbye|see you)[\s!.,]*$", re.I)

_INJECTION = [
    re.compile(r"\b(ignore|disregard|forget|override|bypass)\b.{0,40}\b(previous|prior|above|earlier|all|any|your|the|these|those)\b.{0,30}\b(instructions?|rules?|prompts?|guidelines?|restrictions?|guardrails?|constraints?)\b", re.I | re.S),
    re.compile(r"\b(reveal|show|print|repeat|display|leak|output|tell me|what is|what are)\b.{0,30}\b(your|the)\b.{0,15}\b(system\s+)?(prompt|instructions|rules|guidelines)\b", re.I | re.S),
    re.compile(r"\bsystem\s+prompt\b", re.I),
    re.compile(r"\b(you are now|from now on you|pretend (that )?you are|pretend to be|act as if you (have|had) no)\b", re.I),
    re.compile(r"\b(jailbreak|DAN mode|developer mode|do anything now|no restrictions|without restrictions)\b", re.I),
]


def looks_like_injection(text: str) -> bool:
    return any(p.search(text) for p in _INJECTION)


def pre_check(text: str, assistant: str) -> str | None:
    """A fixed reply when the message can be handled without the AI, otherwise None."""
    if len(text) > MAX_MESSAGE_CHARS:
        return TOO_LONG_REPLY
    if looks_like_injection(text):
        return INJECTION_REPLY[assistant]
    if _GREETING.match(text):
        return GREETING_REPLY[assistant]
    if _THANKS.match(text):
        return THANKS_REPLY[assistant]
    return None
